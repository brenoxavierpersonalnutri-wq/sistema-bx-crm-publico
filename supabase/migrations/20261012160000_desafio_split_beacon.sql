-- =============================================================
-- Desafio Magra e Definida: split /r/desafio (v1..v5) + beacon de
-- conexão e velocidade das páginas. Idempotente: pode rodar de novo.
--
-- 1. page_beacons: uma linha por medição de visitante real.
--    anon/authenticated só fazem INSERT, e só nas colunas do beacon;
--    leitura só para usuário aprovado (mesma regra das tabelas do rotador).
-- 2. rotator_page_beacons: view (security_invoker) que liga o beacon ao
--    clique do rotador pelo cm_click, para o painel Teste de Página.
-- 3. Rotador "desafio" com 5 destinos de peso igual. Não apaga destino
--    existente (apagar destino apaga os cliques dele em cascata): só cria o
--    que falta e acerta url/peso dos que já existem.
-- =============================================================

-- 1. Tabela do beacon ------------------------------------------------------
CREATE TABLE IF NOT EXISTS public.page_beacons (
  id         bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  created_at timestamptz NOT NULL DEFAULT now(),
  page       text NOT NULL,
  variant    text NOT NULL,
  kind       text NOT NULL,
  cm_click   text,
  nav        text,
  ttfb_ms    integer,
  render_ms  integer,
  lcp_ms     integer
);

ALTER TABLE public.page_beacons DROP CONSTRAINT IF EXISTS page_beacons_valores_ok;
ALTER TABLE public.page_beacons ADD CONSTRAINT page_beacons_valores_ok CHECK (
      page    ~ '^[a-z0-9-]{1,40}$'
  AND variant ~ '^[a-z0-9-]{1,40}$'
  AND kind IN ('view', 'vitals')
  AND (cm_click IS NULL OR cm_click ~ '^[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}$')
  AND (nav IS NULL OR nav IN ('doc', 'spa'))
  AND (ttfb_ms   IS NULL OR ttfb_ms   BETWEEN 0 AND 120000)
  AND (render_ms IS NULL OR render_ms BETWEEN 0 AND 120000)
  AND (lcp_ms    IS NULL OR lcp_ms    BETWEEN 0 AND 120000)
);

CREATE INDEX IF NOT EXISTS page_beacons_cm_click_idx ON public.page_beacons (cm_click) WHERE cm_click IS NOT NULL;
CREATE INDEX IF NOT EXISTS page_beacons_page_variant_idx ON public.page_beacons (page, variant, created_at);

ALTER TABLE public.page_beacons ENABLE ROW LEVEL SECURITY;

-- Privilégios: ninguém de fora lê, apaga ou altera; INSERT só nas colunas do beacon
-- (id e created_at ficam com o default do banco).
REVOKE ALL ON public.page_beacons FROM anon, authenticated;
GRANT INSERT (page, variant, kind, cm_click, nav, ttfb_ms, render_ms, lcp_ms)
  ON public.page_beacons TO anon, authenticated;
GRANT SELECT ON public.page_beacons TO authenticated;

DROP POLICY IF EXISTS "Beacon: qualquer visitante insere" ON public.page_beacons;
CREATE POLICY "Beacon: qualquer visitante insere" ON public.page_beacons
  FOR INSERT TO anon, authenticated WITH CHECK (true);

DROP POLICY IF EXISTS "Beacon: aprovados leem" ON public.page_beacons;
CREATE POLICY "Beacon: aprovados leem" ON public.page_beacons
  FOR SELECT TO authenticated USING (public.is_approved(auth.uid()));

-- 2. View do painel -------------------------------------------------------
DROP VIEW IF EXISTS public.rotator_page_beacons;
CREATE VIEW public.rotator_page_beacons
WITH (security_invoker = true) AS
SELECT
  b.id AS beacon_id,
  c.rotator_id,
  c.destination_id,
  b.cm_click,
  b.kind,
  b.nav,
  b.ttfb_ms,
  b.render_ms,
  b.lcp_ms,
  b.created_at
FROM public.page_beacons b
JOIN public.rotator_clicks c ON c.click_id = b.cm_click;

REVOKE ALL ON public.rotator_page_beacons FROM anon;
GRANT SELECT ON public.rotator_page_beacons TO authenticated;

-- 3. Rotador "desafio" ----------------------------------------------------
DO $$
DECLARE
  v_rotator_id uuid;
  v_label text;
  v_url text;
BEGIN
  SELECT id INTO v_rotator_id FROM public.rotator_links WHERE slug = 'desafio' LIMIT 1;

  IF v_rotator_id IS NULL THEN
    INSERT INTO public.rotator_links (slug, name)
    VALUES ('desafio', 'Desafio Magra e Definida (5 promessas)')
    RETURNING id INTO v_rotator_id;
  END IF;

  FOREACH v_label IN ARRAY ARRAY['v1', 'v2', 'v3', 'v4', 'v5'] LOOP
    v_url := 'https://equipe.brenoxavier.com.br/desafio/' || v_label;
    IF EXISTS (SELECT 1 FROM public.rotator_destinations WHERE rotator_id = v_rotator_id AND label = v_label) THEN
      UPDATE public.rotator_destinations
         SET url = v_url, weight = 20
       WHERE rotator_id = v_rotator_id AND label = v_label;
    ELSE
      INSERT INTO public.rotator_destinations (rotator_id, label, url, weight)
      VALUES (v_rotator_id, v_label, v_url, 20);
    END IF;
  END LOOP;
END $$;

